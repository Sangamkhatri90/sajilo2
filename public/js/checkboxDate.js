
document.getElementById("enableDateFrom").addEventListener("change", function () {
    const div = document.getElementById("enabledateTo");
    const div2 = document.getElementById("enabledateFrom");
    if (this.checked) {
        div.style.pointerEvents = ""; // Removes the 'none' value
        div.style.color = "";
        div2.style.pointerEvents = "";
        div2.style.color = "";
    } else {
        div.style.pointerEvents = "none"; // Reapply the 'none' value
        div.style.color = "gray";
        div2.style.pointerEvents = "none";
        div2.style.color = "gray";
    }
});

